// Creates SYNTHETIC demo accounts in the LOCAL development database
// (scripts/dev-db.mjs must be running). Refuses any non-local database.
//
// Accounts use @example.test addresses. Generated passwords are written only to
// .data/dev-accounts.md (gitignored) — never to the console, Git or chat.
// Uses Better Auth's own password hasher (better-auth/crypto), the same one the
// sign-in endpoint verifies against.

import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";

import { hashPassword } from "better-auth/crypto";
import pg from "pg";

if (!existsSync(".env.development.local")) {
  console.error("Run `npm run dev:db` first.");
  process.exit(1);
}
const env = Object.fromEntries(
  readFileSync(".env.development.local", "utf8")
    .split("\n")
    .filter((l) => /^[A-Z_]+=/.test(l))
    .map((l) => [l.slice(0, l.indexOf("=")), l.slice(l.indexOf("=") + 1)]),
);
const authUrl = env.AUTH_DATABASE_URL;
const host = new URL(authUrl).hostname;
if (!["127.0.0.1", "localhost"].includes(host)) {
  console.error("Refusing to seed a non-local database.");
  process.exit(1);
}

const ACCOUNTS = [
  { name: "Ada Verified", email: "ada.verified@example.test", verified: true },
  {
    name: "Ben Unverified",
    email: "ben.unverified@example.test",
    verified: false,
  },
];

const client = new pg.Client({ connectionString: authUrl });
await client.connect();
const lines = [
  "# Synthetic local demo accounts (generated by scripts/dev-seed.mjs; do not commit)",
  "",
  "| Name | Email | Verified | Password |",
  "|---|---|---|---|",
];
try {
  for (const a of ACCOUNTS) {
    const existing = await client.query(
      `SELECT id FROM "user" WHERE email = $1`,
      [a.email],
    );
    if (existing.rowCount) {
      lines.push(
        `| ${a.name} | ${a.email} | ${a.verified} | (unchanged; already seeded) |`,
      );
      continue;
    }
    const password = `Demo-${randomBytes(9).toString("base64url")}`;
    const hash = await hashPassword(password);
    await client.query("BEGIN");
    const user = await client.query(
      `INSERT INTO "user" (name, email, email_verified) VALUES ($1, $2, $3) RETURNING id`,
      [a.name, a.email, a.verified],
    );
    const id = user.rows[0].id;
    await client.query(
      `INSERT INTO account (user_id, account_id, provider_id, password) VALUES ($1, $2, 'credential', $3)`,
      [id, String(id), hash],
    );
    await client.query("COMMIT");
    lines.push(`| ${a.name} | ${a.email} | ${a.verified} | ${password} |`);
  }
} finally {
  await client.end();
}
writeFileSync(".data/dev-accounts.md", `${lines.join("\n")}\n`);
console.log(
  `Seeded ${ACCOUNTS.length} synthetic accounts. Credentials: .data/dev-accounts.md (local only).`,
);
